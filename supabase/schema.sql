-- Base en ligne de l'appli de facturation Ets Barry (Supabase / Postgres).
-- Tables préfixées etsbarry_ pour rester séparées des autres données du projet.

create table if not exists public.etsbarry_admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.etsbarry_clients (
  code text primary key check (code ~ '^[A-Z0-9]{3,12}$'),
  nom text not null check (length(nom) between 1 and 200),
  adresse text not null default '' check (length(adresse) <= 300),
  created_at timestamptz not null default now()
);

create table if not exists public.etsbarry_factures (
  no bigint generated by default as identity primary key,
  code text not null references public.etsbarry_clients (code) on update cascade,
  date text not null,
  nom text not null,
  adresse text not null default '',
  lignes jsonb not null default '[]'::jsonb,
  vir numeric not null default 0 check (vir >= 0),
  banque text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists etsbarry_factures_code_idx on public.etsbarry_factures (code);

-- Vrai si l'utilisateur connecté est administrateur.
create or replace function public.etsbarry_est_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.etsbarry_admins where user_id = (select auth.uid()));
$$;
revoke all on function public.etsbarry_est_admin() from public;
grant execute on function public.etsbarry_est_admin() to authenticated;

alter table public.etsbarry_admins enable row level security;
alter table public.etsbarry_clients enable row level security;
alter table public.etsbarry_factures enable row level security;

-- Un admin peut lire sa propre ligne (pour savoir qu'il est admin). Personne ne peut s'ajouter.
create policy "admin lit sa ligne" on public.etsbarry_admins
  for select to authenticated using (user_id = (select auth.uid()));

-- Seuls les admins lisent et écrivent clients et factures.
create policy "admins gerent les clients" on public.etsbarry_clients
  for all to authenticated using ((select public.etsbarry_est_admin())) with check ((select public.etsbarry_est_admin()));
create policy "admins gerent les factures" on public.etsbarry_factures
  for all to authenticated using ((select public.etsbarry_est_admin())) with check ((select public.etsbarry_est_admin()));

-- Espace client : avec son code, un client lit son compte et ses factures, et rien d'autre.
create or replace function public.etsbarry_compte(p_code text)
returns jsonb language sql stable security definer set search_path = '' as $$
  select case when c.code is null then null else jsonb_build_object(
    'client', jsonb_build_object('code', c.code, 'nom', c.nom, 'adresse', c.adresse),
    'factures', coalesce((
      select jsonb_agg(jsonb_build_object('no', f.no, 'code', f.code, 'date', f.date, 'nom', f.nom,
        'adresse', f.adresse, 'lignes', f.lignes, 'vir', f.vir, 'banque', f.banque) order by f.no desc)
      from public.etsbarry_factures f where f.code = c.code), '[]'::jsonb)
  ) end
  from (select 1) x left join public.etsbarry_clients c on c.code = upper(trim(p_code));
$$;
revoke all on function public.etsbarry_compte(text) from public;
grant execute on function public.etsbarry_compte(text) to anon, authenticated;

